"""DATASETS.md — the public provenance of the model, generated from data/sources.toml (ADR-0010)."""
from . import sources

OUT = sources.REPO / "DATASETS.md"

STATUS_TITLES = [
    ("approved", "Approved for the model (each release lists the sources it actually used in its META)"),
    ("internal", "Awaiting the rights holder's permission (development builds only)"),
    ("eval-only", "Used only to measure accuracy (never in the model)"),
    ("owner-decision", "Pending a project decision (not used)"),
    ("blocked", "Not used"),
]


def render() -> str:
    rows = sources.load()
    out = [
        "# Datasets and provenance",
        "",
        "<!-- Generated by `uv run t3ap datasets-md` from data/sources.toml. Do not edit by hand. -->",
        "",
        "Type3arabi's **code** is licensed under Apache-2.0 (`LICENSE`). Its **language model** — the word and",
        "spelling statistics in `type3arabi.dat` — is licensed under",
        "[CC BY-NC-SA 4.0](https://creativecommons.org/licenses/by-nc-sa/4.0/), because it is learned from the",
        "datasets below, some of which allow non-commercial use only. The model is free and may be shared and",
        "adapted for non-commercial purposes with attribution. No dataset text is redistributed: releases carry",
        "only statistics (word frequencies, spelling rules), and nothing downloaded is stored in this repository.",
        "",
        "Every release's data file records the exact sources it was built from (its `META` section).",
        "",
    ]
    for status, title in STATUS_TITLES:
        group = [r for r in rows if r["status"] == status]
        if not group:
            continue
        out += [f"## {title}", ""]
        if status == "approved":
            out += ["| Dataset | License | Used for |", "|---|---|---|"]
            for r in group:
                name = f"[{r['name']}]({r['url']})" if r["url"].startswith("http") else r["name"]
                roles = ", ".join(r["roles"]) or "—"
                out.append(f"| {name} | {r['license']} | {roles} |")
            out.append("")
            cites = [r for r in group if r.get("citation")]
            if cites:
                out += ["### Citations", ""]
                out += [f"- {r['citation']}" for r in cites]
                out.append("")
        else:
            for r in group:
                name = f"[{r['name']}]({r['url']})" if r["url"].startswith("http") else r["name"]
                out.append(f"- {name} — {r['license']}")
            out.append("")
    return "\n".join(out)


def run() -> int:
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}")
    return 0


def is_current() -> bool:
    return OUT.exists() and OUT.read_text(encoding="utf-8") == render()

